#A shopping list 🛒
shopping_list = ["bread", "milk", "eggs"]

print(shopping_list[0])   # bread
print(shopping_list[1])   # milk
print(shopping_list[2])   # eggs

shopping_list[1] = "butter"
print(shopping_list)

shopping_list.append("sugar")
print(shopping_list)

shopping_list.remove("eggs")
print(shopping_list)